#!/usr/bin/env node
// Generates ApexCore/Analytics/Generated/AnalyticsCatalog.swift from the web's
// analytics sources — the third generator after tokens and DB types
// (docs/ios/architecture.md §13).
//
// The tile builder's vocabulary has one definition: the measure table and
// sport blocklist in src/lib/analytics/spec.ts, the option labels in
// src/lib/analytics/labels.ts, the workout-type labels in
// src/utils/workoutColors.ts. Swift reads the catalog to draw chips and dim
// incompatible pairings; it validates nothing (the server does, D-008).
// Copying 21 measures into Swift by hand is how the phone falls behind the
// web, so this is the only writer of AnalyticsCatalog.swift and `--check`
// runs in scripts/ci-guards.sh.
//
//   node ios/scripts/gen-analytics-catalog.mjs           write
//   node ios/scripts/gen-analytics-catalog.mjs --check   fail if the committed file is stale
//
// Deliberately dependency-free: it must run in a worktree created with
// `git-new.sh --no-install`, before `npm ci`. The three modules load under
// Node's native type stripping because their only imports are `import type`
// (erased at load). draft.ts is NOT loadable (`./spec.js` specifier) and is
// never imported here — keep it that way.
import { writeFileSync, rmSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'ios/Packages/ApexCore/Sources/ApexCore/Analytics/Generated/AnalyticsCatalog.swift');
const SPEC = join(ROOT, 'src/lib/analytics/spec.ts');
const LABELS = join(ROOT, 'src/lib/analytics/labels.ts');
const WORKOUT = join(ROOT, 'src/utils/workoutColors.ts');

const fail = (msg) => {
  console.error(`::error::${msg}`);
  process.exit(1);
};

async function load(path, names) {
  let mod;
  try {
    mod = await import(pathToFileURL(path).href);
  } catch (e) {
    fail(
      `could not import ${path}: ${e.message}\n` +
        `       The catalog generator loads it under Node's type stripping, so every import in it must be ` +
        `\`import type\` and every value a plain literal. If that changed, update ios/scripts/gen-analytics-catalog.mjs.`,
    );
  }
  for (const name of names) if (mod[name] === undefined) fail(`${path} no longer exports ${name}`);
  return mod;
}

const spec = await load(SPEC, [
  'MEASURES', 'MEASURE_IDS', 'WORKOUT_TYPES', 'SPORTS', 'sportCompatible',
  'MAX_SERIES', 'MAX_ROLLING_DAYS', 'DEFAULT_GROUP_LIMIT', 'MAX_GROUP_LIMIT',
]);
const labels = await load(LABELS, [
  'CHART_TYPES', 'BUCKETS', 'RANGE_KINDS', 'PRESETS', 'DISPLAY_UNITS', 'GRADE_SCALES', 'MEAL_TYPES',
  'MEASURE_GROUPS', 'SPORT_OPTIONS', 'GROUP_BY_LABELS', 'DAY_FILTER_MODES', 'OTHER_SPORT_HINT',
]);
const { WORKOUT_COLORS } = await load(WORKOUT, ['WORKOUT_COLORS']);

// ── Cross-checks (the labels test pins these too; here so a --no-install run also fails loudly) ──
const grouped = labels.MEASURE_GROUPS.flatMap((g) => g.ids);
for (const id of spec.MEASURE_IDS) {
  if (!grouped.includes(id)) fail(`measure "${id}" is in spec.ts but no MEASURE_GROUPS entry names it`);
}
for (const id of grouped) {
  if (!spec.MEASURES[id]) fail(`MEASURE_GROUPS names "${id}", which spec.ts does not define`);
}
for (const t of spec.WORKOUT_TYPES) {
  if (!WORKOUT_COLORS[t]?.label) fail(`workout type "${t}" has no label in workoutColors.ts`);
}

// ── Emit ────────────────────────────────────────────────────────────────────
const q = (s) => JSON.stringify(String(s));
const strList = (xs) => `[${xs.map(q).join(', ')}]`;
const options = (xs) => `[\n${xs.map((o) => `        Option(value: ${q(o.value)}, label: ${q(o.label)}),`).join('\n')}\n    ]`;

const aggregations = [...new Set(spec.MEASURE_IDS.flatMap((id) => spec.MEASURES[id].allowedAggs))];
const measures = spec.MEASURE_IDS.map((id) => {
  const m = spec.MEASURES[id];
  const blocked = spec.SPORTS.filter((s) => !spec.sportCompatible(id, s));
  return `        Measure(
            id: ${q(m.id)}, label: ${q(m.label)}, source: ${q(m.source)}, unitKind: ${q(m.unitKind)},
            defaultAgg: ${q(m.defaultAgg)}, allowedAggs: ${strList(m.allowedAggs)},
            allowedGroupBys: ${strList(m.allowedGroupBys)}, aggLevel: ${q(m.aggLevel)},
            blockedSports: ${strList(blocked)}
        ),`;
});

const out = `// GENERATED by ios/scripts/gen-analytics-catalog.mjs — do not edit.
//
// Sources: src/lib/analytics/spec.ts, src/lib/analytics/labels.ts,
// src/utils/workoutColors.ts. Regenerate with
// \`node ios/scripts/gen-analytics-catalog.mjs\`; \`npm run ci:guards\` fails when
// this file and the web drift apart.

/// The tile builder's vocabulary (W9): what the chips offer and which
/// pairings dim. Lookup only — the server validates every draft (D-008).
public enum AnalyticsCatalog {
    public struct Option: Sendable, Hashable, Identifiable {
        public let value: String
        public let label: String
        public var id: String { value }
        public init(value: String, label: String) {
            self.value = value
            self.label = label
        }
    }

    public struct Measure: Sendable, Hashable, Identifiable {
        public let id: String
        public let label: String
        /// completions · set-logs · pitch-logs · cardio-logs · hr-zones · meals
        public let source: String
        /// length · minutes · count · reps · weight · bpm · kcal · grams · grade
        public let unitKind: String
        public let defaultAgg: String
        public let allowedAggs: [String]
        public let allowedGroupBys: [String]
        /// row · day
        public let aggLevel: String
        /// Sports this measure can never mean anything for (the builder dims them).
        public let blockedSports: [String]
        public init(
            id: String, label: String, source: String, unitKind: String, defaultAgg: String,
            allowedAggs: [String], allowedGroupBys: [String], aggLevel: String, blockedSports: [String]
        ) {
            self.id = id
            self.label = label
            self.source = source
            self.unitKind = unitKind
            self.defaultAgg = defaultAgg
            self.allowedAggs = allowedAggs
            self.allowedGroupBys = allowedGroupBys
            self.aggLevel = aggLevel
            self.blockedSports = blockedSports
        }
    }

    public struct MeasureGroup: Sendable, Hashable, Identifiable {
        public let label: String
        public let ids: [String]
        public var id: String { label }
        public init(label: String, ids: [String]) {
            self.label = label
            self.ids = ids
        }
    }

    /// Every measure, in the web's catalog order.
    public static let measures: [Measure] = [
${measures.join('\n')}
    ]

    public static let measuresById: [String: Measure] = Dictionary(uniqueKeysWithValues: measures.map { ($0.id, $0) })

    public static func measure(_ id: String) -> Measure? { measuresById[id] }

    /// The grouped measure picker.
    public static let measureGroups: [MeasureGroup] = [
${labels.MEASURE_GROUPS.map((g) => `        MeasureGroup(label: ${q(g.label)}, ids: ${strList(g.ids)}),`).join('\n')}
    ]

    public static let chartTypes: [Option] = ${options(labels.CHART_TYPES)}

    public static let buckets: [Option] = ${options(labels.BUCKETS)}

    public static let rangeKinds: [Option] = ${options(labels.RANGE_KINDS)}

    public static let presets: [Option] = ${options(labels.PRESETS)}

    public static let displayUnits: [String] = ${strList(labels.DISPLAY_UNITS)}

    public static let gradeScales: [Option] = ${options(labels.GRADE_SCALES)}

    public static let sports: [Option] = ${options(labels.SPORT_OPTIONS)}

    public static let mealTypes: [String] = ${strList(labels.MEAL_TYPES)}

    /// Workout types in the web's order, labelled as the type chips are.
    public static let workoutTypes: [Option] = ${options(spec.WORKOUT_TYPES.map((t) => ({ value: t, label: WORKOUT_COLORS[t].label })))}

    public static let groupByLabels: [String: String] = [
${Object.entries(labels.GROUP_BY_LABELS).map(([k, v]) => `        ${q(k)}: ${q(v)},`).join('\n')}
    ]

    public static let dayFilterModes: [Option] = ${options(labels.DAY_FILTER_MODES)}

    /// Every aggregation some measure allows.
    public static let aggregations: [String] = ${strList(aggregations)}

    public static let maxSeries = ${spec.MAX_SERIES}
    public static let maxRollingDays = ${spec.MAX_ROLLING_DAYS}
    public static let defaultGroupLimit = ${spec.DEFAULT_GROUP_LIMIT}
    public static let maxGroupLimit = ${spec.MAX_GROUP_LIMIT}

    /// Shown under "Which workouts" when no workout carries the sport "other".
    public static let otherSportHint = ${q(labels.OTHER_SPORT_HINT)}
}
`;

if (process.argv.includes('--check')) {
  const tmp = join(tmpdir(), `apex-analytics-catalog-${process.pid}.swift`);
  writeFileSync(tmp, out);
  const r = spawnSync('diff', ['-u', OUT, tmp], { stdio: 'inherit' });
  rmSync(tmp, { force: true });
  if (r.status !== 0) {
    console.error(
      `::error::ios/Packages/ApexCore/Sources/ApexCore/Analytics/Generated/AnalyticsCatalog.swift is stale — ` +
        `the analytics catalog changed on the web without regenerating the iOS copy.`,
    );
    console.error(`       Run 'node ios/scripts/gen-analytics-catalog.mjs' and commit the result.`);
    process.exit(1);
  }
  console.log('ok: AnalyticsCatalog.swift matches the web analytics sources');
} else {
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}
