#!/usr/bin/env node
// Generates ApexCore/Onboarding/Generated/OnboardingCatalog.swift from
// src/lib/onboarding/content.ts — the fourth generator after tokens, DB types
// and the analytics catalog (docs/ios/architecture.md §13, D-035).
//
// Every word a new user reads during setup has one definition, content.ts, so
// the web's welcome flow and checklist cannot drift apart. The phone reads
// the same words from this file: the steps, the checklist rows, the notes,
// the guide URL. It decides nothing with them — which rows are done comes
// from the server (`GET /api/profile` → `onboarding.setup`, the
// src/lib/onboarding/progress.ts logic, D-008).
//
//   node ios/scripts/gen-onboarding-catalog.mjs           write
//   node ios/scripts/gen-onboarding-catalog.mjs --check   fail if the committed file is stale
//
// Dependency-free, like the analytics generator: content.ts has no imports at
// all, so it loads under Node's native type stripping in a --no-install
// worktree.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT = join(ROOT, 'ios/Packages/ApexCore/Sources/ApexCore/Onboarding/Generated/OnboardingCatalog.swift');
const CONTENT = join(ROOT, 'src/lib/onboarding/content.ts');

const fail = (msg) => {
  console.error(`::error::${msg}`);
  process.exit(1);
};

let content;
try {
  content = await import(pathToFileURL(CONTENT).href);
} catch (e) {
  fail(
    `could not import ${CONTENT}: ${e.message}\n` +
      `       The catalog generator loads it under Node's type stripping, so it must stay import-free ` +
      `(or \`import type\` only) with plain literals. If that changed, update ios/scripts/gen-onboarding-catalog.mjs.`,
  );
}
for (const name of ['WELCOME_STEPS', 'CHECKLIST_ITEMS', 'EXTRA_NOTES', 'GUIDE_URL']) {
  if (content[name] === undefined) fail(`${CONTENT} no longer exports ${name}`);
}
const { WELCOME_STEPS, CHECKLIST_ITEMS, EXTRA_NOTES, GUIDE_URL } = content;

// ── Cross-checks: the Swift side switches over these, so a new kind or id has to be seen here ──
const KINDS = ['copy-template', 'open-profile', 'connect-coros'];
const CHECKLIST_IDS = ['template', 'key', 'goal', 'coros', 'connector'];
for (const step of WELCOME_STEPS) {
  if (step.action && !KINDS.includes(step.action.kind)) fail(`welcome step "${step.id}" uses unknown action kind "${step.action.kind}" — add it to KINDS here and to OnboardingCatalog.ActionKind`);
  if (step.iosBody !== undefined && (typeof step.iosBody !== 'string' || !step.iosBody.trim())) {
    fail(`welcome step "${step.id}" has an empty iosBody — drop the field to use body`);
  }
  if (step.iosBody === step.body) fail(`welcome step "${step.id}" repeats body in iosBody — drop the field`);
}
for (const item of CHECKLIST_ITEMS) {
  if (!CHECKLIST_IDS.includes(item.id)) fail(`checklist item "${item.id}" is not in CHECKLIST_IDS — add it here and to OnboardingCatalog.ChecklistID`);
  if (!KINDS.includes(item.action.kind)) fail(`checklist item "${item.id}" uses unknown action kind "${item.action.kind}"`);
}
const seen = new Set();
for (const step of WELCOME_STEPS) {
  if (seen.has(step.id)) fail(`duplicate welcome step id "${step.id}"`);
  seen.add(step.id);
}

// ── Emit ────────────────────────────────────────────────────────────────────
const q = (s) => JSON.stringify(String(s));
const kindCase = (kind) => ({ 'copy-template': '.copyTemplate', 'open-profile': '.openProfile', 'connect-coros': '.connectCoros' })[kind];
const action = (a) => (a ? `Action(label: ${q(a.label)}, kind: ${kindCase(a.kind)})` : 'nil');
const link = (l) => (l ? `Link(label: ${q(l.label)}, href: ${q(l.href)})` : 'nil');

// A step's `iosBody` replaces its `body` here and nowhere else: the web keeps
// its own sentence, the phone gets the one that is true of the phone (no week
// view, D-009). The marker comment keeps the swap visible to a reader diffing
// this file against content.ts.
const steps = WELCOME_STEPS.map((s) => `${s.iosBody ? '        // body: content.ts `iosBody` — the web says something else here.\n' : ''}        Step(
            id: ${q(s.id)}, title: ${q(s.title)},
            body: ${q(s.iosBody ?? s.body)},
            action: ${action(s.action)}, link: ${link(s.link)}, requiresCoros: ${!!s.requiresCoros}
        ),`);
const items = CHECKLIST_ITEMS.map((i) => `        ChecklistItem(
            id: .${i.id}, label: ${q(i.label)},
            hint: ${q(i.hint)},
            action: ${action(i.action)}, requiresCoros: ${!!i.requiresCoros}
        ),`);

const out = `// GENERATED by ios/scripts/gen-onboarding-catalog.mjs — do not edit.
//
// Source: src/lib/onboarding/content.ts. Regenerate with
// \`node ios/scripts/gen-onboarding-catalog.mjs\`; \`npm run ci:guards\` fails when
// this file and the web drift apart.

/// Every word a new user reads during setup (W13, U32): the welcome flow's
/// steps, the checklist rows, the notes under it. Copy only — which rows are
/// done is the server's answer (\`ProfileResponse.onboarding.setup\`, D-008).
public enum OnboardingCatalog {
    /// What a step's or row's button does. The app maps each to its own
    /// screen; the web maps them to its hooks (useOnboardingActions).
    public enum ActionKind: String, Sendable, Hashable {
        case copyTemplate = "copy-template"
        case openProfile = "open-profile"
        case connectCoros = "connect-coros"
    }

    /// The contract between the copy and the progress signals.
    public enum ChecklistID: String, Sendable, Hashable, CaseIterable {
        case template, key, goal, coros, connector
    }

    public struct Action: Sendable, Hashable {
        public let label: String
        public let kind: ActionKind
        public init(label: String, kind: ActionKind) {
            self.label = label
            self.kind = kind
        }
    }

    public struct Link: Sendable, Hashable {
        public let label: String
        public let href: String
        public init(label: String, href: String) {
            self.label = label
            self.href = href
        }
    }

    public struct Step: Sendable, Hashable, Identifiable {
        public let id: String
        public let title: String
        /// The step's words for this app: content.ts's \`iosBody\` where it has
        /// one, else its \`body\`. The web renders \`body\` regardless.
        public let body: String
        public let action: Action?
        /// Opens outside the flow — the flow is one-shot, don't navigate out of it.
        public let link: Link?
        /// Dropped entirely when no watch provider is configured for the deployment.
        public let requiresCoros: Bool
        public init(id: String, title: String, body: String, action: Action?, link: Link?, requiresCoros: Bool) {
            self.id = id
            self.title = title
            self.body = body
            self.action = action
            self.link = link
            self.requiresCoros = requiresCoros
        }
    }

    public struct ChecklistItem: Sendable, Hashable, Identifiable {
        public let id: ChecklistID
        public let label: String
        public let hint: String
        public let action: Action
        public let requiresCoros: Bool
        public init(id: ChecklistID, label: String, hint: String, action: Action, requiresCoros: Bool) {
            self.id = id
            self.label = label
            self.hint = hint
            self.action = action
            self.requiresCoros = requiresCoros
        }
    }

    /// The user guide. Absolute because the app is a SPA — a relative path 404s.
    public static let guideURL = ${q(GUIDE_URL)}

    /// The welcome flow, in order. Filter \`requiresCoros\` by the deployment.
    public static let welcomeSteps: [Step] = [
${steps.join('\n')}
    ]

    /// The getting-started checklist, in order. Filter \`requiresCoros\` by the deployment.
    public static let checklistItems: [ChecklistItem] = [
${items.join('\n')}
    ]

    public static func checklistItem(_ id: ChecklistID) -> ChecklistItem? {
        checklistItems.first { $0.id == id }
    }

    /// Shown under the checklist: real features, but nothing to tick off.
    public static let extraNotes: [String] = [
${EXTRA_NOTES.map((n) => `        ${q(n)},`).join('\n')}
    ]

    /// The three rows the Schedule tab's setup card shows (the web's NUDGE_IDS):
    /// the ones the profile answers without a further request.
    public static let nudgeIDs: [ChecklistID] = [.template, .key, .goal]
}
`;

if (process.argv.includes('--check')) {
  let current = '';
  try { current = readFileSync(OUT, 'utf8'); } catch { /* missing counts as stale */ }
  if (current !== out) {
    fail(`${OUT} is stale — run \`node ios/scripts/gen-onboarding-catalog.mjs\` and commit the result`);
  }
  console.log('ok: OnboardingCatalog.swift matches src/lib/onboarding/content.ts');
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, out);
  console.log(`wrote ${OUT}`);
}
